def configure_matplotlib() -> None:
    plt.rcParams.update(
        {
            "font.size": 8,
            "axes.titlesize": 9,
            "axes.labelsize": 9,
            "legend.fontsize": 7.5,
            "xtick.labelsize": 7.5,
            "ytick.labelsize": 7.5,
            "axes.spines.top": False,
            "axes.spines.right": False,
            "pdf.fonttype": 42,  # embed TrueType fonts (no Type 3 in the PDF)
            "ps.fonttype": 42,
        }
    )


def save_figure(figure: plt.Figure, stem: Path) -> None:
    figure.savefig(stem.with_suffix(".pdf"))
    figure.savefig(stem.with_suffix(".png"), dpi=200)
    plt.close(figure)


def row_major_legend(handles, labels, columns: int):
    """Matplotlib fills legends column-major; reorder for row-major reading."""
    rows = math.ceil(len(handles) / columns)
    order = [
        row * columns + column
        for column in range(columns)
        for row in range(rows)
        if row * columns + column < len(handles)
    ]
    return [handles[index] for index in order], [labels[index] for index in order]


def plot_metric_grid(
    data: dict[tuple[str, str, int], Row],
    metric: str,
    ylabel: str,
    stem: Path,
    yscale: str,
) -> None:
    algorithms = present_algorithms(data)
    distributions = present_distributions(data)

    figure, axes = plt.subplots(
        2, 2, figsize=(7.0, 5.2), sharex=True, sharey=True, constrained_layout=True
    )

    for axis, distribution in zip(axes.flat, distributions):
        for algorithm in algorithms:
            points = sorted(
                (key[2], getattr(row, metric))
                for key, row in data.items()
                if key[0] == algorithm and key[1] == distribution
            )
            if not points:
                continue
            axis.plot(
                [point[0] for point in points],
                [point[1] for point in points],
                color=COLORS[algorithm],
                marker=MARKERS[algorithm],
                markersize=3.2,
                linewidth=1.1,
                label=ALGORITHM_LABELS[algorithm],
            )

        axis.set_xscale("log")
        if yscale == "log":
            axis.set_yscale("log")
        elif yscale == "symlog":
            axis.set_yscale("symlog", linthresh=10.0, linscale=0.6)
        axis.set_title(DISTRIBUTION_LABELS[distribution])
        axis.grid(True, which="major", alpha=0.25, linewidth=0.6)
        axis.grid(True, which="minor", alpha=0.12, linewidth=0.4)

    for axis in axes.flat[len(distributions) :]:
        axis.axis("off")

    for axis in axes[-1, :]:
        axis.set_xlabel("Veri boyutu $n$")
    figure.supylabel(ylabel)

    handles, labels = [], []
    for axis in axes.flat:
        handles, labels = axis.get_legend_handles_labels()
        if handles:
            break
    handles, labels = row_major_legend(handles, labels, 4)
    figure.legend(
        handles,
        labels,
        loc="outside lower center",
        ncol=4,
        frameon=False,
    )
    save_figure(figure, stem)


def plot_distribution_effect(
    data: dict[tuple[str, str, int], Row], stem: Path
) -> None:
    algorithms = present_algorithms(data)
    distributions = present_distributions(data)

    columns = 4
    rows = math.ceil((len(algorithms) + 1) / columns)
    figure, axes = plt.subplots(
        rows, columns, figsize=(7.0, 1.9 * rows), sharex=True, constrained_layout=True
    )
    flat_axes = axes.flat

    for index, algorithm in enumerate(algorithms):
        axis = flat_axes[index]
        for distribution in distributions:
            points = sorted(
                (key[2], row.mean_ms)
                for key, row in data.items()
                if key[0] == algorithm and key[1] == distribution
            )
            if not points:
                continue
            axis.plot(
                [point[0] for point in points],
                [point[1] for point in points],
                color=DISTRIBUTION_COLORS[distribution],
                marker=DISTRIBUTION_MARKERS[distribution],
                markersize=3.0,
                linewidth=1.1,
                label=DISTRIBUTION_LABELS[distribution],
            )
        axis.set_title(ALGORITHM_LABELS[algorithm])
        axis.set_xscale("log")
        axis.set_yscale("log")
        axis.grid(True, which="major", alpha=0.25, linewidth=0.6)
        axis.grid(True, which="minor", alpha=0.12, linewidth=0.4)

    legend_axis = flat_axes[len(algorithms)]
    handles, labels = flat_axes[0].get_legend_handles_labels()
    legend_axis.legend(handles, labels, loc="center", frameon=False)
    legend_axis.axis("off")
    for axis in list(flat_axes)[len(algorithms) + 1 :]:
        axis.axis("off")

    figure.supxlabel("Veri boyutu $n$")
    figure.supylabel("Ortalama süre (ms)")
    save_figure(figure, stem)


