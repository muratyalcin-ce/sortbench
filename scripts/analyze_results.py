def detect_cpu() -> str:
    try:
        with open("/proc/cpuinfo", encoding="utf-8") as handle:
            for line in handle:
                if line.startswith("model name"):
                    return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return platform.processor() or "unknown"


def detect_cpu_topology() -> tuple[int, int]:
    """Returns (physical cores, logical processors); falls back to os.cpu_count."""
    logical = os.cpu_count() or 1
    physical = None
    try:
        with open("/proc/cpuinfo", encoding="utf-8") as handle:
            for line in handle:
                if line.startswith("cpu cores") and physical is None:
                    physical = int(line.split(":", 1)[1].strip())
    except (OSError, ValueError):
        pass
    return (physical or logical, logical)


def detect_ram() -> str:
    try:
        with open("/proc/meminfo", encoding="utf-8") as handle:
            for line in handle:
                if line.startswith("MemTotal:"):
                    kibibytes = int(line.split()[1])
                    return f"{kibibytes / 1024 / 1024:.1f} GiB"
    except (OSError, ValueError):
        pass
    return "unknown"


def detect_os() -> str:
    try:
        with open("/etc/os-release", encoding="utf-8") as handle:
            for line in handle:
                if line.startswith("PRETTY_NAME="):
                    return line.split("=", 1)[1].strip().strip('"')
    except OSError:
        pass
    return platform.platform()


def detect_compiler() -> str:
    for candidate in (os.environ.get("CXX"), "c++", "g++", "clang++"):
        if not candidate:
            continue
        try:
            result = subprocess.run(
                [candidate, "--version"],
                capture_output=True,
                text=True,
                timeout=5,
                check=False,
            )
        except (OSError, subprocess.SubprocessError):
            continue
        if result.returncode == 0 and result.stdout.strip():
            return result.stdout.splitlines()[0].strip()
    return "unknown"


def detect_meson() -> str:
    try:
        result = subprocess.run(
            ["meson", "--version"], capture_output=True, text=True, timeout=5, check=False
        )
        if result.returncode == 0:
            return result.stdout.strip()
    except (OSError, subprocess.SubprocessError):
        pass
    return "unknown"


def render_environment_table(
    csv_path: Path, data: dict[tuple[str, str, int], Row], source: Path, args
) -> str:
    physical_cores, logical = detect_cpu_topology()
    repetitions = sorted({row.repetitions for row in data.values()})
    sizes = present_sizes(data)
    run_date = datetime.fromtimestamp(csv_path.stat().st_mtime).strftime("%Y-%m-%d")
    compiler = args.compiler or detect_compiler()

    rows = [
        ("İşlemci", detect_cpu(), True),
        ("Çekirdek / iş parçacığı", f"{physical_cores} / {logical}", True),
        ("Bellek (RAM)", detect_ram(), True),
        ("İşletim sistemi", detect_os(), True),
        ("Derleyici", compiler, True),
        ("Dil standardı", "C++17", True),
        ("Derleme sistemi", f"Meson {detect_meson()} + Ninja (optimize ikili)", True),
        ("IDE / çalıştırma ortamı", "Komut satırı", True),
        ("Veri boyutları", ", ".join(map(str, sizes)), True),
        (
            "Dağılımlar",
            "rastgele, sıralı, ters sıralı, kısmen sıralı",
            True,
        ),
        ("Temel tohum", str(args.seed), True),
        (
            "Yineleme",
            f"{', '.join(map(str, repetitions))} ölçülmüş + {args.warmup} ısınma turu",
            True,
        ),
        (
            "Komut",
            r"\texttt{\detokenize{sortbench --reps "
            + str(repetitions[-1])
            + " --warmup "
            + str(args.warmup)
            + "}}",
            False,
        ),
        ("Çalıştırma tarihi", run_date, True),
    ]

    lines = [
        r"\begin{table}[htbp]",
        r"  \centering",
        r"  \caption{Ölçüm ortamı ve deney parametreleri.}",
        r"  \label{tab:environment}",
        r"  \footnotesize",
        r"  \begin{tabular}{@{}p{0.24\linewidth}p{0.68\linewidth}@{}}",
        r"    \toprule",
        r"    Öğe & Değer \\",
        r"    \midrule",
    ]
    for item, value, escape_value in rows:
        escaped = tex_escape(value) if escape_value else value
        lines.append(f"    {item} & {escaped} \\\\")
    lines += [r"    \bottomrule", r"  \end{tabular}", r"\end{table}"]
    return GENERATED_HEADER.format(source=source.name) + "\n".join(lines) + "\n"


