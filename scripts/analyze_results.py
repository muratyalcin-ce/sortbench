def render_metric_table(
    data: dict[tuple[str, str, int], Row],
    metric: str,
    caption: str,
    label: str,
    formatter,
    source: Path,
) -> str:
    algorithms = present_algorithms(data)
    distributions = present_distributions(data)
    sizes = present_sizes(data)
    column_count = len(sizes)

    lines = [
        r"\begin{table}[htbp]",
        r"  \centering",
        f"  \\caption{{{caption}}}",
        f"  \\label{{{label}}}",
        r"  \footnotesize",
        r"  \setlength{\tabcolsep}{3pt}",
        f"  \\begin{{tabular}}{{ll{'r' * column_count}}}",
        r"    \toprule",
        f"    & \\multicolumn{{{column_count}}}{{c}}{{Veri boyutu $n$}} \\\\",
        f"    \\cmidrule(lr){{3-{2 + column_count}}}",
        "    Algoritma & Dağılım & "
        + " & ".join(f"${group_digits(size)}$" for size in sizes)
        + r" \\",
        r"    \midrule",
    ]

    for algorithm_index, algorithm in enumerate(algorithms):
        for distribution_index, distribution in enumerate(distributions):
            first_column = ALGORITHM_LABELS[algorithm] if distribution_index == 0 else ""
            cells = []
            for size in sizes:
                row = data.get((algorithm, distribution, size))
                cells.append(formatter(getattr(row, metric)) if row else "--")
            lines.append(
                f"    {first_column} & {DISTRIBUTION_LABELS[distribution]} & "
                + " & ".join(cells)
                + r" \\"
            )
        if algorithm_index != len(algorithms) - 1:
            lines.append(r"    \midrule")

    lines += [r"    \bottomrule", r"  \end{tabular}", r"\end{table}"]
    return GENERATED_HEADER.format(source=source.name) + "\n".join(lines) + "\n"


def growth_exponent(
    data: dict[tuple[str, str, int], Row],
    algorithm: str,
    distribution: str,
    metric: str = "mean_ms",
    minimum_size: int = 1000,
) -> float | None:
    """Least-squares slope of log(metric) against log(n)."""
    points = sorted(
        (key[2], getattr(row, metric))
        for key, row in data.items()
        if key[0] == algorithm
        and key[1] == distribution
        and key[2] >= minimum_size
        and getattr(row, metric) > 0.0
    )
    if len(points) < 2:
        return None
    sizes = np.log([point[0] for point in points])
    values = np.log([point[1] for point in points])
    slope, _intercept = np.polyfit(sizes, values, 1)
    return float(slope)


def render_summary_table(
    data: dict[tuple[str, str, int], Row], source: Path
) -> str:
    algorithms = present_algorithms(data)
    auxiliary = {}
    for algorithm in algorithms:
        for key, row in data.items():
            if key[0] == algorithm:
                auxiliary[algorithm] = row.aux_memory
                break

    lines = [
        r"\begin{table}[htbp]",
        r"  \centering",
        r"  \caption{Kuramsal karmaşıklık, yardımcı bellek ve ölçülen büyüme "
        r"üssü $b$. $b$, $n \ge 1000$ için ortalama çalışma süresinin $n$'ye "
        r"göre log--log doğrusal regresyon eğimidir; $b \approx 2$ ikinci "
        r"dereceden, $b \approx 1{,}1$ ise $n \log n$ büyümeyi gösterir.}",
        r"  \label{tab:summary}",
        r"  \small",
        r"  \setlength{\tabcolsep}{6pt}",
        r"  \begin{tabular}{lrrrrl}",
        r"    \toprule",
        r"    Algoritma & Ortalama durum & Yardımcı bellek & $b$ (rastgele) & $b$ (sıralı) & Kararlı \\",
        r"    \midrule",
    ]

    for algorithm in algorithms:
        lines.append(
            f"    {ALGORITHM_LABELS[algorithm]} & {THEORY[algorithm]} & "
            f"{fmt_aux_memory(auxiliary[algorithm])} & "
            f"{fmt_exponent(growth_exponent(data, algorithm, 'random'))} & "
            f"{fmt_exponent(growth_exponent(data, algorithm, 'sorted'))} & "
            f"{STABLE[algorithm]} \\\\"
        )

    lines += [
        r"    \bottomrule",
        r"  \end{tabular}",
        r"  \par\smallskip",
        r"  \footnotesize Shell Sort $n/2, n/4, \dots, 1$ gap dizisini; Quick "
        r"Sort ise üçün ortancası (median-of-three) pivot seçimini kullanır.",
        r"\end{table}",
    ]
    return GENERATED_HEADER.format(source=source.name) + "\n".join(lines) + "\n"


