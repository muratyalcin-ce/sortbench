def parse_arguments() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--csv",
        type=Path,
        default=Path("assets/plots/results.csv"),
        help="aggregated results CSV (default: assets/plots/results.csv)",
    )
    parser.add_argument(
        "--outdir",
        type=Path,
        default=Path("assets/plots"),
        help="artifact directory (default: assets/plots)",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="dataset seed recorded in the environment table (default: 42)",
    )
    parser.add_argument(
        "--warmup",
        type=int,
        default=1,
        help="number of discarded warm-up runs (default: 1)",
    )
    parser.add_argument(
        "--compiler",
        default=None,
        help="compiler string for the environment table (default: auto-detect)",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_arguments()
    csv_path: Path = args.csv
    outdir: Path = args.outdir

    if not csv_path.is_file():
        raise SystemExit(f"CSV not found: {csv_path}")

    data = load_results(csv_path)
    repetitions = sorted({row.repetitions for row in data.values()})
    repetitions_text = " / ".join(map(str, repetitions))
    tables_dir = outdir / "tables"
    figures_dir = outdir / "figures"
    tables_dir.mkdir(parents=True, exist_ok=True)
    figures_dir.mkdir(parents=True, exist_ok=True)

    configure_matplotlib()

    (tables_dir / "tab_time.tex").write_text(
        render_metric_table(
            data,
            "mean_ms",
            "Algoritma ve veri dağılımına göre ortalama çalışma süresi "
            f"({repetitions_text} yineleme ortalaması, ms).",
            "tab:time",
            fmt_time,
            csv_path,
        ),
        encoding="utf-8",
    )
    (tables_dir / "tab_comparisons.tex").write_text(
        render_metric_table(
            data,
            "mean_comparisons",
            "Algoritma ve veri dağılımına göre ortalama karşılaştırma sayısı "
            f"({repetitions_text} yineleme ortalaması). $10^5$ ve üzeri değerler "
            "bilimsel gösterimle verilmiştir.",
            "tab:comparisons",
            fmt_count,
            csv_path,
        ),
        encoding="utf-8",
    )
    (tables_dir / "tab_moves.tex").write_text(
        render_metric_table(
            data,
            "mean_moves",
            "Algoritma ve veri dağılımına göre ortalama veri hareketi sayısı "
            f"({repetitions_text} yineleme ortalaması). Bir yer değiştirme üç "
            "hareket sayılmıştır; $10^5$ ve üzeri değerler bilimsel gösterimle "
            "verilmiştir.",
            "tab:moves",
            fmt_count,
            csv_path,
        ),
        encoding="utf-8",
    )
    (tables_dir / "tab_summary.tex").write_text(
        render_summary_table(data, csv_path), encoding="utf-8"
    )
    (tables_dir / "tab_environment.tex").write_text(
        render_environment_table(csv_path, data, csv_path, args), encoding="utf-8"
    )

    plot_metric_grid(
        data,
        "mean_ms",
        "Ortalama süre (ms)",
        figures_dir / "fig_time_vs_n",
        "log",
    )
    plot_metric_grid(
        data,
        "mean_comparisons",
        "Ortalama karşılaştırma sayısı",
        figures_dir / "fig_comparisons_vs_n",
        "log",
    )
    plot_metric_grid(
        data,
        "mean_moves",
        "Ortalama veri hareketi",
        figures_dir / "fig_moves_vs_n",
        "symlog",
    )
    plot_distribution_effect(data, figures_dir / "fig_distribution_effect")

    render_include_files(outdir, csv_path, repetitions_text)

    with (outdir / "growth_exponents.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(["algorithm", "distribution", "exponent_time"])
        for algorithm in present_algorithms(data):
            for distribution in present_distributions(data):
                exponent = growth_exponent(data, algorithm, distribution)
                writer.writerow(
                    [
                        algorithm,
                        distribution,
                        "" if exponent is None else f"{exponent:.4f}",
                    ]
                )

    print(f"read {len(data)} rows from {csv_path}")
    print(f"algorithms: {', '.join(present_algorithms(data))}")
    print(f"sizes: {', '.join(map(str, present_sizes(data)))}")
    print(f"wrote tables to {tables_dir}")
    print(f"wrote figures to {figures_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
