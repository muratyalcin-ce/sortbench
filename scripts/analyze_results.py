@dataclass(frozen=True)
class Row:
    algorithm: str
    distribution: str
    n: int
    repetitions: int
    mean_ms: float
    stddev_ms: float
    min_ms: float
    max_ms: float
    mean_comparisons: float
    mean_moves: float
    aux_memory: str
    aux_bytes: int
    verified: bool


REQUIRED_COLUMNS = {
    "algorithm",
    "distribution",
    "n",
    "repetitions",
    "mean_time_ms",
    "stddev_time_ms",
    "min_time_ms",
    "max_time_ms",
    "mean_comparisons",
    "mean_moves",
    "aux_memory",
    "aux_bytes",
    "verified",
}


def load_results(path: Path) -> dict[tuple[str, str, int], Row]:
    data: dict[tuple[str, str, int], Row] = {}

    with path.open(newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        missing = REQUIRED_COLUMNS.difference(reader.fieldnames or [])
        if missing:
            raise SystemExit(f"{path}: missing CSV columns: {', '.join(sorted(missing))}")

        for raw in reader:
            row = Row(
                algorithm=raw["algorithm"],
                distribution=raw["distribution"],
                n=int(raw["n"]),
                repetitions=int(raw["repetitions"]),
                mean_ms=float(raw["mean_time_ms"]),
                stddev_ms=float(raw["stddev_time_ms"]),
                min_ms=float(raw["min_time_ms"]),
                max_ms=float(raw["max_time_ms"]),
                mean_comparisons=float(raw["mean_comparisons"]),
                mean_moves=float(raw["mean_moves"]),
                aux_memory=raw["aux_memory"],
                aux_bytes=int(raw["aux_bytes"]),
                verified=raw["verified"].strip() in {"1", "true", "True"},
            )
            key = (row.algorithm, row.distribution, row.n)
            if key in data:
                raise SystemExit(f"{path}: duplicate row for {key}")
            data[key] = row

    if not data:
        raise SystemExit(f"{path}: no data rows")

    unverified = sum(1 for row in data.values() if not row.verified)
    if unverified:
        print(
            f"warning: {unverified} row(s) are not verified; the report should "
            "mention this.",
            file=sys.stderr,
        )
    return data


def present_algorithms(data: dict[tuple[str, str, int], Row]) -> list[str]:
    found = {key[0] for key in data}
    return [algorithm for algorithm in ALGORITHM_ORDER if algorithm in found]


def present_distributions(data: dict[tuple[str, str, int], Row]) -> list[str]:
    found = {key[1] for key in data}
    return [distribution for distribution in DISTRIBUTION_ORDER if distribution in found]


def present_sizes(data: dict[tuple[str, str, int], Row]) -> list[int]:
    return sorted({key[2] for key in data})


# ---------------------------------------------------------------------------
# LaTeX number formatting
# ---------------------------------------------------------------------------


def tex_escape(text: str) -> str:
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    return "".join(replacements.get(character, character) for character in text)


def group_digits(value: int) -> str:
    return f"{value:,}".replace(",", r"\,")


def fmt_time(value: float) -> str:
    """Compact millisecond value: 18 233, 182.3, 27.82, 0.0076, 0.00011."""
    if value == 0.0:
        return "$0$"
    if value >= 1000.0:
        text = f"{value:,.0f}"
    elif value >= 100.0:
        text = f"{value:,.1f}"
    elif value >= 1.0:
        text = f"{value:.2f}"
    elif value >= 0.01:
        text = f"{value:.4f}"
    else:
        text = f"{value:.5f}"
    return "$" + text.replace(",", r"\,") + "$"


def fmt_count(value: float) -> str:
    """Integer with thin separators below 1e5, scientific notation above."""
    if value == 0.0:
        return "$0$"
    if value < 100000.0:
        return "$" + group_digits(int(round(value))) + "$"

    exponent = int(math.floor(math.log10(value)))
    mantissa = value / 10.0**exponent
    if round(mantissa, 2) >= 10.0:
        mantissa /= 10.0
        exponent += 1
    return rf"${mantissa:.2f}\times10^{{{exponent}}}$"


def fmt_aux_memory(text: str) -> str:
    """CSV stores 'O(1)' / 'O(log n)' / 'O(n)'; typeset log as an operator."""
    if "log" in text:
        return r"$O(\log n)$"
    return f"${text}$"


def fmt_exponent(value: float | None) -> str:
    return "--" if value is None else f"${value:.2f}$"


